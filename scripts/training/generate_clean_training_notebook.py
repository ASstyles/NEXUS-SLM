                "\n",
                "def prepare_masked_dataset(records: List[Dict[str, Any]], max_len: int = 384) -> Dataset:\n",
                "    input_ids_list = []\n",
                "    labels_list = []\n",
                "    for r in records:\n",
                "        target = {\n",
                "            'category': r['category'],\n",
                "            'priority': r['priority'],\n",
                "            'language': r['language'],\n",
                "            'requires_human': r['requires_human'],\n",
