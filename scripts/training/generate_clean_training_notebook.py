                "        \n",
                "        prompt_ids = tokenizer.encode(prompt_str, add_special_tokens=False)\n",
                "        full_ids = tokenizer.encode(full_str, add_special_tokens=False)\n",
                "        \n",
                "        if full_ids[:len(prompt_ids)] == prompt_ids:\n",
                "            p_len = len(prompt_ids)\n",
                "        else:\n",
                "            comp_ids = tokenizer.encode(completion_str, add_special_tokens=False)\n",
                "            p_len = max(0, len(full_ids) - len(comp_ids))\n",
                "            \n",
                "        lbls = [-100] * p_len + full_ids[p_len:]\n",
                "        input_ids_list.append(full_ids[:max_len])\n",
                "        labels_list.append(lbls[:max_len])\n",
                "        \n",
